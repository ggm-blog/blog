#!/usr/bin/env python3
"""Integration checks against pinned Quarto; work only in an isolated copy.

Run: python3 tests/test-prelaunch.py /path/to/quarto
"""
from datetime import datetime, timedelta, date
from pathlib import Path
from zoneinfo import ZoneInfo
import importlib.util
import os
import re
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parent.parent
QUARTO = str(Path(sys.argv[1]).resolve()) if len(sys.argv) > 1 else shutil.which('quarto')
TODAY = datetime.now(ZoneInfo('America/Los_Angeles')).date()
SLUGS = ['2026-12-parser-grammar', '2026-11-ggm-origin-story',
         '2026-11-tensor-tension', '2026-11-surprising-riposte']


def main():
    with tempfile.TemporaryDirectory(prefix='ggm-prelaunch-') as temp:
        work = Path(temp)
        names = subprocess.check_output(['git', 'ls-files', '--cached', '--others', '--exclude-standard'], cwd=ROOT, text=True).splitlines()
        # Copy project files, not unrelated user archives/notes or render caches.
        for name in names:
            if name in ['CHANGES.md', 'dillon-bib.zip', 'ggm-first-posts.zip']:
                continue
            src, dst = ROOT / name, work / name
            if src.is_file():
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dst)
        sources = {slug: (work / 'posts' / slug / 'index.qmd').read_text() for slug in SLUGS}

        def post(slug, offset, draft=None, featured=None):
            front, body = sources[slug][4:].split('\n---', 1)
            front = re.sub(r'^date:.*$', f'date: "{TODAY + timedelta(days=offset)}"', front, flags=re.M)
            front = re.sub(r'^draft:.*\n?', '', front, flags=re.M)
            if draft is not None:
                front += f'\ndraft: {str(draft).lower()}'
            if featured is not None:
                front = re.sub(r'^featured:.*$', f'featured: {str(featured).lower()}', front, flags=re.M)
            (work / 'posts' / slug / 'index.qmd').write_text('---\n' + front + '\n---' + body)

        def render(staging=False, error=None):
            env = os.environ.copy()
            env.pop('QUARTO_PROFILE', None)
            if staging:
                env['QUARTO_PROFILE'] = 'staging'
            result = subprocess.run([QUARTO, 'render'], cwd=work, env=env, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            if error:
                assert result.returncode != 0 and error in result.stdout, result.stdout
                return
            assert result.returncode == 0, result.stdout

        def output(name):
            return (work / '_site' / name).read_text()

        def visible(slugs):
            home = output('index.html')
            urls = [entry.findtext('link') for entry in ET.fromstring(output('index.xml')).findall('./channel/item')]
            search = output('search.json')
            sitemap = output('sitemap.xml')
            nav = (work / '_nav-posts.yml').read_text()
            for slug in SLUGS:
                shown = slug in slugs
                html = output(f'posts/{slug}/index.html')
                assert ('<main' in html) == shown, (slug, 'page')
                assert any(slug in url for url in urls) == shown, (slug, 'RSS')
                assert (slug in search) == shown, (slug, 'search')
                assert (slug in sitemap) == shown, (slug, 'sitemap')
                # The project draft list includes hidden paths, so check href only.
                assert (f'href: posts/{slug}/index.qmd' in nav) == shown, (slug, 'navbar')
                assert (f'href="./posts/{slug}/index.html"' in home) == shown, (slug, 'listing')
            assert len(urls) == len(slugs)
            assert 'anchorjs-link' not in re.search(r'<div class="home-listing">[\s\S]*?</main>', home)[0]
            assert 'author-status-editor' in output('contributors.html')

        tim, origin, ellen, brian = SLUGS
        post(tim, 1, draft=False)
        post(origin, 1)
        post(ellen, 8, draft=True)
        post(brian, 15, draft=True)
        render()
        visible([])
        assert 'No posts published yet.' in output('index.html')
        for slug in [tim, origin]:
            assert (work / 'posts' / slug / '_metadata.yml').read_text().startswith('# generated by pre-render date gate\n')
        print('PASS future date gate, including explicit draft:false', flush=True)

        render(staging=True)
        visible(SLUGS)
        assert output('index.html').count('ggm-badge-draft') == 2
        for slug in [ellen, brian]:
            assert 'id="quarto-draft-alert"' in output(f'posts/{slug}/index.html')
        for slug in [tim, origin]:
            assert not (work / 'posts' / slug / '_metadata.yml').exists()
        print('PASS staging lists/indexes/feeds all posts and marks drafts', flush=True)

        post(tim, 0, draft=False)
        post(origin, 0)
        render()
        visible([tim, origin])
        home = output('index.html')
        hero = re.search(r'<article class="home-post home-latest"[\s\S]*?</article>', home)[0]
        assert tim in hero and origin not in hero
        assert home.count('class="home-post home-pinned"') == 1
        assert 'home-post home-compact' not in home and 'All posts</h2>' not in home
        assert home.count('ggm-badge-pinned') == 1
        for slug in [tim, origin]:
            assert not (work / 'posts' / slug / '_metadata.yml').exists()
        # Pagefind sees only these public HTML pages: hidden posts are blank stubs.
        result = subprocess.run(['npx', '--yes', 'pagefind', '--site', '_site'], cwd=work, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        assert result.returncode == 0, result.stdout
        print('PASS launch-day Latest/Pinned tie-break, empty archive, and Pagefind index', flush=True)

        post(origin, 0, featured=False)
        render()
        visible([tim, origin])
        assert 'ggm-badge-pinned' not in output('index.html')
        assert 'All posts</h2>' in output('index.html')
        assert origin in re.search(r'<article class="home-post home-latest"[\s\S]*?</article>', output('index.html'))[0]
        post(origin, 0, featured=True)
        post(tim, -1)
        render()
        visible([tim, origin])
        hero = re.search(r'<article class="home-post home-latest"[\s\S]*?</article>', output('index.html'))[0]
        assert origin in hero and 'ggm-badge-pinned' in hero
        assert 'home-post home-pinned' not in output('index.html')
        print('PASS no featured posts and featured Latest without duplication', flush=True)

        path = work / 'posts' / tim / 'index.qmd'
        good = path.read_text()
        path.write_text(re.sub(r'^date:.*$', 'date: "2026-02-30"', good, flags=re.M))
        render(error=f'posts/{tim}/index.qmd: date must be a valid YYYY-MM-DD date')
        path.write_text(re.sub(r'^date:.*\n', '', good, flags=re.M))
        render(error=f'posts/{tim}/index.qmd date')
        path.write_text(good.replace('- tim-hunter', '- nonexistent-author'))
        render(error=f'posts/{tim}/index.qmd: unknown author slug "nonexistent-author"')
        post(tim, 1)
        metadata = work / 'posts' / tim / '_metadata.yml'
        metadata.write_text('# hand-maintained\ntoc: false\n')
        render(error=f'date gate cannot replace unmarked posts/{tim}/_metadata.yml')
        assert metadata.read_text() == '# hand-maintained\ntoc: false\n'
        render(staging=True)
        assert metadata.read_text() == '# hand-maintained\ntoc: false\n'
        print('PASS invalid/missing dates, unknown author, and unmarked metadata protection', flush=True)

        # Verify the actual launch dates at Los Angeles midnight, not UTC midnight.
        metadata.unlink()  # This test created the hand-maintained fixture above.
        for slug in SLUGS:
            (work / 'posts' / slug / 'index.qmd').write_text(sources[slug])
        gate = work / 'scripts/prepare-authors.ts'
        original_gate = gate.read_text()
        env = os.environ.copy()
        env.pop('QUARTO_PROFILE', None)
        for instant, count in [('2026-11-17T07:59:59Z', 0), ('2026-11-17T08:00:00Z', 2)]:
            gate.write_text(original_gate.replace('.formatToParts(new Date());',
                f'.formatToParts(new Date("{instant}"));'))
            result = subprocess.run([QUARTO, 'run', 'scripts/prepare-authors.ts'], cwd=work,
                env=env, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            assert result.returncode == 0, result.stdout
            assert (work / 'generated/posts.yml').read_text().count('- path:') == count
        print('PASS real November 17 schedule at Los Angeles midnight (UTC boundary)', flush=True)

        # All fixture post edits above are front matter; real sources are unchanged.
        for slug in SLUGS:
            assert (ROOT / 'posts' / slug / 'index.qmd').read_text() == sources[slug]
    spec = importlib.util.spec_from_file_location('next_publish', ROOT / 'scripts/next-publish-date.py')
    helper = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(helper)
    assert helper.next_date(date(2026, 11, 17), 1, 1) == date(2026, 11, 24)
    assert helper.next_date(date(2026, 11, 11), 1, 2) == date(2026, 11, 24)
    print('PASS next-date strict-after-today and --n logic; source posts untouched')


if __name__ == '__main__':
    main()
